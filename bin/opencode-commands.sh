#!/usr/bin/env sh
# Generate OpenCode slash-command wrappers for installed skills.
#
# OpenCode discovers skills natively (agent-invoked via the `skill` tool) but
# its "/" menu only lists commands. This script bridges the gap: for every
# skill in the skills dir it writes a thin command wrapper that tells the
# agent to load that skill, so `/orch`, `/handoff`, etc. autocomplete in the TUI.
#
# Usage: opencode-commands.sh [skills-dir] [commands-dir]
# Defaults: ~/.agents/skills -> ~/.config/opencode/commands
# Re-run after `npx skills add/update` to pick up new skills. Idempotent;
# only files marked "generated by opencode-commands.sh" are overwritten.

set -eu

SKILLS_DIR="${1:-$HOME/.agents/skills}"
OUT_DIR="${2:-$HOME/.config/opencode/commands}"
MARKER="generated by opencode-commands.sh"

mkdir -p "$OUT_DIR"

for skill_md in "$SKILLS_DIR"/*/SKILL.md; do
  [ -f "$skill_md" ] || continue
  name=$(sed -n 's/^name:[[:space:]]*//p' "$skill_md" | head -1)
  [ -n "$name" ] || continue
  # statusline configures a TUI footer that does not exist in OpenCode
  case "$name" in statusline) continue ;; esac

  out="$OUT_DIR/$name.md"
  if [ -f "$out" ] && ! grep -q "$MARKER" "$out"; then
    echo "skip $out (hand-written, not overwriting)"
    continue
  fi

  desc=$(sed -n 's/^description:[[:space:]]*//p' "$skill_md" | head -1 |
    tr -d '"' | cut -c1-100)

  cat >"$out" <<EOF
---
description: "$desc"
---
<!-- $MARKER -->
Load the \`$name\` skill with the skill tool and follow it exactly, treating the following as its arguments: \$ARGUMENTS
EOF
  echo "wrote $out"
done
